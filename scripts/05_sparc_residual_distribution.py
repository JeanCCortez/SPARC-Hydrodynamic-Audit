A0_THRESHOLD = 1.2001e-10  
KPC_TO_M = 3.086e19
KM_TO_M = 1000.0

SPARC_DATA_DIR = r"E:\Documentos\rrt\art2\new\Rotmod_LTG"
OUTPUT_DIR = "sparc_outputs"
os.makedirs(OUTPUT_DIR, exist_ok=True)

def calculate_hydrodynamic_velocity(row, upsilon_d=0.5, upsilon_b=0.7):
    """Calculates the velocity using the Hydrodynamic Limit Ansatz."""
    v2_bar = (row['Vgas'] * np.abs(row['Vgas'])) + (upsilon_d * row['Vdisk'] * np.abs(row['Vdisk'])) + (upsilon_b * row['Vbul'] * np.abs(row['Vbul']))
    if v2_bar <= 0: return np.nan 
    g_bar = (v2_bar * (KM_TO_M**2)) / (row['Rad'] * KPC_TO_M)
    nu = 0.5 + np.sqrt(0.25 + (A0_THRESHOLD / g_bar))
    return np.sqrt((v2_bar * (KM_TO_M**2)) * nu) / KM_TO_M

def parse_sparc_file(filepath):
    """Robust parser for SPARC catalog .dat files."""
    with open(filepath, 'r') as f: lines = f.readlines()
    header, data = [], []
    for line in lines:
        line = line.strip()
        if not line: continue
        if line.startswith('#'):
            if 'RAD' in line.upper() or 'VOBS' in line.upper(): 
                header = line.replace('#', '').strip().split()
        else: data.append(line.split())
    if not header or not data: return None
    df = pd.DataFrame(data)
    if len(header) >= len(df.columns): df.columns = header[:len(df.columns)]
    else: df.columns = header + list(df.columns[len(header):])
    rename_map = {}
    for col in df.columns:
        c = str(col).upper()
        if 'RAD' in c or c == 'R': rename_map[col] = 'Rad'
        elif 'VOBS' in c: rename_map[col] = 'Vobs'
        elif 'VGAS' in c: rename_map[col] = 'Vgas'
        elif 'VDISK' in c: rename_map[col] = 'Vdisk'
        elif 'VBUL' in c: rename_map[col] = 'Vbul'
    df = df.rename(columns=rename_map).loc[:, ~df.columns.duplicated()]
    if 'Vbul' not in df.columns: df['Vbul'] = 0.0
    for col in ['Rad', 'Vobs', 'Vgas', 'Vdisk', 'Vbul']:
        if col in df.columns: df[col] = pd.to_numeric(df[col], errors='coerce')
    return df.dropna(subset=['Rad', 'Vobs', 'Vgas', 'Vdisk'])

def plot_real_residual_distribution():
    print("="*80)
    print(" 📊 GENERATING RESIDUAL HISTOGRAM WITH 100% REAL DATA 📊")
    print("="*80)
    
    all_files = [f for f in os.listdir(SPARC_DATA_DIR) if f.endswith('.dat')]
    real_percentage_residuals = []
    
    for file in all_files:
        filepath = os.path.join(SPARC_DATA_DIR, file)
        df = parse_sparc_file(filepath)
        if df is None or len(df) == 0: continue
        
        df['V_pred'] = df.apply(lambda row: calculate_hydrodynamic_velocity(row, upsilon_d=0.5), axis=1)
        df = df.dropna(subset=['V_pred'])
        
        if len(df) == 0: continue
        
        # Signed percentage residual error: (V_obs - V_pred) / V_obs * 100
        pct_res = ((df['Vobs'] - df['V_pred']) / df['Vobs']) * 100
        real_percentage_residuals.extend(pct_res.values)

    real_percentage_residuals = np.array(real_percentage_residuals)
    mean_res = np.nanmean(real_percentage_residuals)
    mae_res = np.nanmean(np.abs(real_percentage_residuals))
    
    # Histogram plotting
    fig_hist, ax_hist = plt.subplots(figsize=(9, 6))
    
    # Clip extreme anomalies (>100%) generated by galactic center geometric chaos for legibility
    plot_data = real_percentage_residuals[(real_percentage_residuals > -100) & (real_percentage_residuals < 100)]
    
    ax_hist.hist(plot_data, bins=60, color='#8B0000', alpha=0.75, edgecolor='black')
    
    ax_hist.axvline(mean_res, color='black', linestyle='dashed', linewidth=2.5, label=f'Systematic Bias = {mean_res:.2f}%')
    ax_hist.axvline(mae_res, color='blue', linestyle='dotted', linewidth=2, label=f'Mean Abs. Error (MAE) = {mae_res:.2f}%')
    ax_hist.axvline(-mae_res, color='blue', linestyle='dotted', linewidth=2)
    
    # Title entirely sanitized from internal working names
    ax_hist.set_title('Global Distribution of Hydrodynamic Velocity Residuals (Raw SPARC Data)', fontsize=14, fontweight='bold')
    ax_hist.set_xlabel('Velocity Residual [(Obs - Pred) / Obs] (%)', fontsize=12)
    ax_hist.set_ylabel('Number of Radial Data Points', fontsize=12)
    ax_hist.legend(fontsize=11)
    ax_hist.grid(True, alpha=0.3)
    
    fig_hist.tight_layout()
    output_path = os.path.join(OUTPUT_DIR, "sparc_real_global_residuals.png")
    fig_hist.savefig(output_path, dpi=300)
    plt.close(fig_hist)
    
    print(f" -> Real histogram generated successfully!")
    print(f" -> Saved at: {output_path}")
    print(f" -> Systematic Bias      : {mean_res:.2f}%")
    print(f" -> Raw Dispersion (MAE) : {mae_res:.2f}%")

if __name__ == "__main__":
    plot_real_residual_distribution()